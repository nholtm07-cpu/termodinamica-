export function clonePresetInputs(caseId: HeatCaseId): Record<string, Parameter> {
  const src = BOOK_CASE_DEFINITIONS[caseId].defaultInputs;
  const out: Record<string, Parameter> = {};
  for (const [k, p] of Object.entries(src)) {
    out[k] = { ...p, domain: { ...p.domain } };
  }
  return out;
}

export function detectModifiedFields(
  caseId: HeatCaseId,
  inputs: Record<string, Parameter>
): string[] {
  const base = BOOK_CASE_DEFINITIONS[caseId].defaultInputs;
  const modified: string[] = [];
  for (const [k, p] of Object.entries(base)) {
    const cur = inputs[k];
    if (cur && Math.abs(cur.value - p.value) > 1e-12) {
      modified.push(k);
    }
  }
  return modified;
}
